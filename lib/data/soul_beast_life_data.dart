  Map<String, int> effects = const <String, int>{},
  List<String> addTags = const <String>[],
  List<String> requiredTags = const <String>[],
  List<String> forbiddenTags = const <String>[],
  String? arcId,
  int arcStage = 0,
  int repeatLimit = 0,
  String? relationshipId,
  String? relationshipName,
  String relationshipType = '命运关系',
  int trustDelta = 0,
  int affectionDelta = 0,
  int minRelationshipTrust = 0,
  int maxRelationshipTrust = 100,
  bool relationshipMustBeAlive = false,
  EncounterSpec? encounter,
}) => StoryEvent(
  id: id,
  title: title,
  description: description,
  weight: weight,
  route: RouteType.soulBeast,
  minBeastYears: minBeastYears,
  eraIds: eraIds,
  minProtagonistYear: minProtagonistYear,
  maxProtagonistYear: maxProtagonistYear,
  effects: effects,
  addTags: addTags,
  requiredTags: requiredTags,
  forbiddenTags: forbiddenTags,
  arcId: arcId,
  arcStage: arcStage,
  repeatLimit: repeatLimit,
  relationshipId: relationshipId,
  relationshipName: relationshipName,
  relationshipType: relationshipType,
  trustDelta: trustDelta,
  affectionDelta: affectionDelta,
  minRelationshipTrust: minRelationshipTrust,
  maxRelationshipTrust: maxRelationshipTrust,
  relationshipMustBeAlive: relationshipMustBeAlive,
  encounter: encounter,
