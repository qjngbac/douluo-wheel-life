    soulBeastProfilesByName[name];

double soulBeastContextMultiplier(
  SoulBeastProfile profile,
  Character character,
  HuntContext? hunt,
) {
  var multiplier = 1.0;
  final beastText = '${profile.name}${profile.trait}';
  final soulText = character.martialSoul ?? '';
  const affinityGroups = <List<String>>[
    <String>['雷', '电', '霆'],
    <String>['火', '炎', '焰', '凰'],
    <String>['冰', '霜', '雪', '寒'],
    <String>['水', '海', '潮', '鲸'],
    <String>['木', '藤', '草', '花', '树', '生命'],
    <String>['影', '暗', '幽', '冥'],
    <String>['光', '星', '圣', '阳'],
    <String>['梦', '心', '精神', '幻'],
    <String>['龙', '兽', '血脉'],
    <String>['风', '速', '翼'],
  ];
  for (final group in affinityGroups) {
    final soulMatches = group.any(soulText.contains);
    if (soulMatches && group.any(beastText.contains)) multiplier += .7;
  }
  if (character.timeline?.contains('海') ?? false) {
    if (const <String>['海', '水', '潮', '鲸'].any(beastText.contains)) {
      multiplier += .25;
    }
  }
  final methodId = hunt?.methodId;
  final habitat = hunt?.habitat;
  if (habitat != null) {
    multiplier *= profile.habitats.contains(habitat) ? 1.55 : .88;
  }
  if (methodId == 'ring-alone' && profile.quality >= 5) multiplier *= .58;
  if (methodId == 'ring-help' && profile.quality >= 5) multiplier *= 1.45;
  if (methodId == 'ring-clue' && profile.quality >= 4) multiplier *= 1.25;
  if (methodId == 'ring-sacrifice' && profile.requiredTags.isNotEmpty) {
    multiplier *= 1.8;
  }
  final personality = personalityTraitFromTags(character.tags);
  if (personality == PersonalityTrait.careful && profile.quality >= 6) {
    multiplier *= .82;
  }
  if (personality == PersonalityTrait.brave && profile.quality >= 5) {
    multiplier *= 1.18;
  }
  return multiplier.clamp(.25, 4.0).toDouble();
}

List<WheelOption> soulBeastOptionsForRing(
  Iterable<WheelOption> options,
  int ringNumber,
) => options
    .where((option) {
      final profile = soulBeastProfileForId(option.id);
      return profile == null || profile.supportsRing(ringNumber);
    })
    .toList(growable: false);
