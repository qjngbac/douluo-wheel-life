import '../domain/models.dart';

class SoulBeastProfile {
  const SoulBeastProfile(
    this.id,
    this.name, {
    required this.weight,
    this.minRing = 1,
    this.maxRing = 9,
    this.quality = 1,
    this.affinity = 100,
    this.trait = '灵息',
    this.habitats = const <String>['通用'],
    this.requiredTags = const <String>[],
    this.specialColor,
    this.specialYearsLower,
    this.specialYearsUpper,
  });

  final String id;
  final String name;
  final double weight;
  final int minRing;
  final int maxRing;
  final int quality;
  final int affinity;
  final String trait;
  final List<String> habitats;
  final List<String> requiredTags;
  final RingColor? specialColor;
  final int? specialYearsLower;
  final int? specialYearsUpper;

  bool supportsRing(int ringNumber) =>
      ringNumber >= minRing && ringNumber <= maxRing;

  WheelOption toOption() => WheelOption(
    id: id,
    text: name,
    weight: weight,
    requiredTags: requiredTags,
  );
}

