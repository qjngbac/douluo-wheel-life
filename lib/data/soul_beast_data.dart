    <String, SoulBeastProfile>{
      for (final profile in soulBeastLibrary) profile.name: profile,
    };

List<WheelOption> buildSoulBeastOptions() => soulBeastLibrary
    .map((profile) => profile.toOption())
    .toList(growable: false);

