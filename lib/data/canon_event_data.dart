StoryEvent _sideCharacterEvent({
  required String key,
  required String era,
  required int index,
  required String name,
  required String place,
}) {
  final template = switch (index) {
    0 => (
      title: '在$place接受$name的救援',
      description: '你在$place因魂力透支落后于队伍，$name冒险折返，把你从封锁线前带回安全区域。',
      type: '救命之交',
      trust: 12,
      affection: 4,
      effect: const <String, int>{'luck': 2},
    ),
    1 => (
      title: '在$place与$name竞争名额',
      description: '你与$name为同一个晋级名额反复交手，彼此拆解战术，也逐渐承认对方的实力。',
      type: '长期竞争者',
      trust: 3,
      affection: 0,
      effect: const <String, int>{'soulPower': 1},
    ),
    2 => (
      title: '与$name共同研习魂技',
      description: '$name在$place与你交换修炼记录，一处长期被忽略的魂力衔接问题因此得到修正。',
      type: '研修伙伴',
      trust: 8,
      affection: 3,
      effect: const <String, int>{'soulPower': 2},
    ),
    3 => (
      title: '和$name执行隐秘任务',
      description: '你与$name受命潜入$place侦查敌情，撤离时选择互相掩护，没有把同伴留在险地。',
      type: '任务搭档',
      trust: 10,
      affection: 1,
      effect: const <String, int>{'luck': 1},
    ),
    4 => (
      title: '$name托付一段秘密',
      description: '$name在$place把一条可能牵动多方势力的线索交给你，并要求你暂时不要向任何人透露。',
      type: '秘密盟友',
      trust: 7,
      affection: 2,
      effect: const <String, int>{'luck': 2},
    ),
    _ => (
      title: '与$name阵营立场分歧',
      description: '在$place的局势交锋中，你与$name因所属阵营和利益立场的不同产生激烈分歧，各自退后一步保持冷淡戒备。',
      type: '阵营对立',
      trust: -12,
      affection: -5,
      effect: const <String, int>{'luck': -2},
    ),
  };
  return StoryEvent(
    id: '$key-companion-$index',
    title: template.title,
    description: template.description,
    weight: switch (index) {
      0 => 7,
      1 => 8,
      2 => 7,
      3 => 6,
      4 => 5,
      _ => 3,
    },
    route: RouteType.human,
    minAge: 7 + index,
    maxAge: 48,
    eraIds: <String>[era],
    minProtagonistYear: -2,
    maxProtagonistYear: 42,
    effects: template.effect,
    relationshipId: '$key-companion-$index',
    relationshipName: name,
    relationshipType: template.type,
    trustDelta: template.trust,
    affectionDelta: template.affection,
    repeatLimit: 1,
  );
}
